def env_list(name, default=()):
    """Lista separada por comas desde el entorno, sin espacios ni barras finales."""
    raw = os.getenv(name, '')
    values = [item.strip().rstrip('/') for item in raw.split(',') if item.strip()]
    return values or list(default)


